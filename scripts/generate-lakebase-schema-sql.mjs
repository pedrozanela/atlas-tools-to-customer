#!/usr/bin/env node
/**
 * Generate serverless-safe Lakebase bootstrap SQL for prebuilt deployments.
 *
 * The Databricks notebook can apply these SQL files with psycopg, avoiding
 * `npx prisma db push` on serverless notebook compute.
 */

import { spawnSync } from "node:child_process";
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const outputDir = resolve(root, "resources/lakebase-schema");
const npx = process.platform === "win32" ? "npx.cmd" : "npx";

mkdirSync(outputDir, { recursive: true });

function runPrismaDiff(app) {
  const cwd = resolve(root, "apps", app);
  const out = resolve(outputDir, `${app}.sql`);
  const result = spawnSync(
    npx,
    [
      "prisma",
      "migrate",
      "diff",
      "--from-empty",
      "--to-schema",
      "prisma/schema.prisma",
      "--script",
      "--config",
      "prisma.config.ts",
      "--output",
      out,
    ],
    { cwd, encoding: "utf8", stdio: "pipe" },
  );
  if (result.status !== 0) {
    process.stderr.write(result.stderr || result.stdout || "");
    throw new Error(`Failed to generate ${app} Lakebase schema SQL`);
  }

  const sql = readFileSync(out, "utf8");
  if (!sql.includes("CREATE TABLE")) {
    throw new Error(`${out} did not contain CREATE TABLE statements`);
  }
  writeFileSync(
    out,
    [
      `-- Generated by scripts/generate-lakebase-schema-sql.mjs for apps/${app}/prisma/schema.prisma.`,
      "-- Used by notebooks/deploy_atlas.py for serverless prebuilt deployments.",
      sql.trim(),
      "",
    ].join("\n"),
  );
  console.log(`[lakebase-schema] generated ${out}`);
}

function writeMasSchema() {
  const source = readFileSync(resolve(root, "apps/mas/lib/db.ts"), "utf8");
  const match = source.match(/const SCHEMA_DDL = `([\s\S]*?)`;\n/);
  if (!match) {
    throw new Error("Could not extract MAS SCHEMA_DDL from apps/mas/lib/db.ts");
  }

  const out = resolve(outputDir, "mas.sql");
  writeFileSync(
    out,
    [
      "-- Generated by scripts/generate-lakebase-schema-sql.mjs from apps/mas/lib/db.ts.",
      "-- Used by notebooks/deploy_atlas.py for serverless prebuilt deployments.",
      match[1].trim(),
      "",
    ].join("\n"),
  );
  console.log(`[lakebase-schema] generated ${out}`);
}

runPrismaDiff("forge");
runPrismaDiff("waf");
writeMasSchema();
